// Publisher polish (2026-10-12) on the real build: the week board (touch and keyboard), the
// receipt's "what it really paid" line, and Otis's listing on the board.
import { test, expect } from './fixtures.js';
import { boot, tapLabel, settleMorning, step, auditText } from './helpers.js';

test('the week board opens from the morning, reads cleanly, and closes (touch)', async ({ page }) => {
  await boot(page);
  await settleMorning(page);
  await tapLabel(page, 'This week');
  expect(await page.evaluate(() => window.__game.weekOpen)).toBe(true);
  const audit = await auditText(page, 'week board');
  expect(audit, audit.join('\n')).toEqual([]);
  await page.screenshot({ path: 'test-results/week-board.png' });
  await tapLabel(page, 'Close');
  expect(await page.evaluate(() => window.__game.weekOpen)).toBe(false);
});

test('the week board by keyboard: Escape closes it, and it never survives a screen change', async ({ page }) => {
  await boot(page);
  await settleMorning(page);
  await page.evaluate(() => { window.__game.weekOpen = true; window.__game.step(2 / 60); });
  await page.keyboard.press('Escape');
  await step(page, 4 / 60);
  expect(await page.evaluate(() => window.__game.weekOpen)).toBe(false);
  await page.evaluate(() => { const g = window.__game; g.weekOpen = true; g.goBrowse(); });
  await step(page, 1);
  expect(await page.evaluate(() => ({ phase: window.__game.phase, open: window.__game.weekOpen }))).toEqual({ phase: 'BROWSE', open: false });
});

test('a finished job says what it really paid per hour', async ({ page }) => {
  await boot(page);
  await settleMorning(page);
  const r = await page.evaluate(() => {
    const g = window.__game, s = g.state;
    g.goBrowse(); g.step(1);
    const pick = s.todayGigs.find((x) => !x.hasQTE && g.canAffordGig(x).ok) || s.todayGigs.find((x) => g.canAffordGig(x).ok);
    g.acceptGig(pick);
    let guard = 0;
    while (g.phase !== 'RESULTS' && guard++ < 200) {
      g.step(0.7);   // let each transition finish, the way a player waits for it
      if (g.transition) continue;
      if (g.phase === 'TRAVEL') g.startGig();
      else if (g.phase !== 'GIG') continue;
      else if (g.qteKind === 'ei') g.finishEIGame({ success: true, score: 70, effects: {}, summary: 'x' });
      else if (g.qteKind === 'skill') g.finishGig({ success: true, score: 70 });
      else if (g.pendingOutcome) g.continueOutcome();
      else if (g.node) g.choose(g.node.choices[0]);
      else if (!g.qte) g.afterChoices();
    }
    g.resultsT = 5; g.step(1 / 60);
    return { phase: g.phase, net: g.results && g.results.net, hours: pick.hours };
  });
  expect(r.phase).toBe('RESULTS');
  expect(r.net.hours).toBe(r.hours);
  expect(r.net.perHour).toBe(Math.round(r.net.kept / r.hours));
  // (The settled receipt, net line included, is audited in readability.spec.js.)
  await step(page, 2);
  await page.screenshot({ path: 'test-results/receipt-net.png' });
});

test("Otis's studio job is on the board two days after he asks", async ({ page }) => {
  await boot(page);
  await settleMorning(page);
  // Otis asked two days ago; the game's own day change posts his job.
  await page.evaluate(() => { const g = window.__game; g.state.otisArc = { stage: 1, day: g.state.day - 1 }; g.goEvening(); });
  // Next morning is generated by the game's own day change.
  await page.evaluate(() => { const g = window.__game; if (g.billsOpen) { for (const k of ['rent', 'phone', 'food']) g.payBill(k); g.closeBills(); } if (g.wrapUpOpen) g.finishWrapUp(); g.sleep(); g.step(2); });
  await settleMorning(page);
  const board = await page.evaluate(() => { const g = window.__game; g.goBrowse(); g.step(1); return g.state.todayGigs.map((x) => x.title); });
  expect(board[0]).toBe("Soundproof Otis's Practice Room");
  await page.screenshot({ path: 'test-results/otis-listing.png' });
});
